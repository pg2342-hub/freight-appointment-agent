// Writes public/data.js for the page: the go-live gate results per setup (from gate/results/*.json,
// written by golive-gate) and the preloaded example threads (recorded runs through the real loop and tools).
// Run: npx tsx scripts/build_page.ts
import { readFileSync, writeFileSync } from "node:fs";
import world from "../seed/world.json" with { type: "json" };
import cases from "../gate/cases.json" with { type: "json" };
import { calendarFor } from "../src/calendar";
import { runCase } from "../src/eval";
import { ScriptedModel } from "../src/model";
import type { World } from "../src/world";

const W = world as unknown as World;
const SETUPS = [
  { key: "scripted", name: "Scripted stand-in", what: "Follows the appointment rules exactly; checks the plumbing" },
  { key: "scripted-naive", name: "Always book", what: "Books the first open slot for the first PO; never hands off" },
];

const gate = SETUPS.map((s) => {
  const r = JSON.parse(readFileSync(new URL(`../gate/results/${s.key}.json`, import.meta.url), "utf8"));
  const crit = new Set(r.checks.filter((c: any) => c.critical).map((c: any) => c.id));
  return {
    ...s,
    decision: r.decision,
    runs: r.runs,
    passed: Math.min(...r.summary.by_run.map((x: any) => x.passed)),
    critical: Math.max(...r.summary.by_run.map((x: any) => x.critical)),
    cases: r.cases.map((c: any) => {
      const failed = [...new Set(c.runs.flatMap((x: any) => x.failed_checks))] as string[];
      return { id: c.id, group: c.group, title: c.title, failed, critical: failed.some((f) => crit.has(f)) };
    }),
  };
});

const EXAMPLE_IDS = [["f01", "Book a delivery"], ["f11", "Carrier running late"], ["f13", "Portal fails"], ["f25", "Hazmat load"]];
const examples = [];
for (const [id, label] of EXAMPLE_IDS) {
  const c = (cases as any).cases.find((x: any) => x.id === id);
  const { output, steps } = await runCase(c.input, W, (w, b) => new ScriptedModel(c.input.facts, b, w));
  examples.push({
    id,
    label,
    received_at: c.input.received_at,
    thread: c.input.thread,
    result: output,
    calendar: calendarFor(W, steps, W),
    steps: steps.filter((s) => s.kind === "tool").map((s: any) => ({ name: s.name, ok: s.ok, status: s.output?.status ?? null, error: s.error ?? null })),
  });
}

const cases25 = (cases as any).cases.map((c: any) => ({ id: c.id, group: c.group, title: c.title, from: c.input.thread[0].from, body: c.input.thread.map((m: any) => m.body).join("\n\n") }));
writeFileSync(new URL("../public/data.js", import.meta.url), `// Generated by scripts/build_page.ts. Do not edit.\nwindow.DATA = ${JSON.stringify({ gate, examples, cases: cases25 })};\n`);
console.log("wrote public/data.js", gate.map((g) => `${g.key} ${g.passed}/25 ${g.decision}`).join(", "));
