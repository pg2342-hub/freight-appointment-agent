// Writes public/desk/data.js for the desk console: the 40 recorded threads (25 dev + 15 held-out) with
// Claude's three graded runs each, the facilities and loads from the seed, and the gate results per setup.
// Everything comes from seed/world.json, gate/cases.json, gate/holdout.json and gate/results/*.json.
// Run: node scripts/build_desk.mjs
import { existsSync, readFileSync, writeFileSync } from "node:fs";

const read = (p) => JSON.parse(readFileSync(new URL(`../${p}`, import.meta.url), "utf8"));
const world = read("seed/world.json");
const suites = [
  { key: "dev", cases: read("gate/cases.json").cases, prefix: "" },
  { key: "holdout", cases: read("gate/holdout.json").cases, prefix: "holdout-" },
];

const results = (prefix, setup) => {
  const p = `gate/results/${prefix}${setup}.json`;
  return existsSync(new URL(`../${p}`, import.meta.url)) ? read(p) : null;
};

const threads = [];
for (const s of suites) {
  const claude = results(s.prefix, "claude");
  const byId = new Map(claude.cases.map((c) => [c.id, c]));
  for (const c of s.cases) {
    const r = byId.get(c.id);
    threads.push({
      id: c.id,
      suite: s.key,
      tier: c.group,
      title: c.title,
      received_at: c.input.received_at,
      emails: c.input.thread.map((m) => ({ from: m.from, body: m.body })),
      facility_response: c.input.facility_response ?? null,
      expected: c.expected,
      runs: r.runs.map((x) => ({
        run: x.run,
        passed: x.passed,
        failed: x.failed_checks,
        cost_usd: x.cost_usd,
        latency_s: x.latency_s,
        error: x.error || null,
        output: (({ steps, ...o }) => o)(x.output ?? {}),
        steps: x.output?.steps ?? null, // every tool call, when the recorded run carries them
      })),
    });
  }
}

const SETUPS = [
  ["claude", "Claude", "claude-opus-5-5 in the tool loop, deployed on Cloudflare"],
  ["scripted", "Scripted stand-in", "Follows the appointment rules exactly; checks the plumbing"],
  ["scripted-naive", "Always book", "Books the first open slot for the first PO; never hands off"],
];
const gate = {};
for (const s of suites) {
  gate[s.key] = SETUPS.map(([key, name, what]) => {
    const r = results(s.prefix, key);
    if (!r) return null;
    return {
      key, name, what,
      decision: r.decision,
      by_run: r.summary.by_run,
      cost_usd: r.summary.total_cost_usd,
      latency_s: r.summary.mean_latency_s,
    };
  }).filter(Boolean);
}
const checks = read("gate/results/claude.json").checks;

const facilities = world.facilities.map((f) => ({
  id: f.id, name: f.name, tz: f.tz, channel: f.channel, open: f.open, close: f.close, days: f.days,
  notice_hours: f.notice_hours, holidays: f.holidays, booked: f.booked, fcfs: f.fcfs,
}));
const loads = world.loads.map((l) => ({
  load_no: l.load_no, po: l.customer_po, pickup: l.pickup, delivery: l.delivery, carrier: l.carrier ?? null, hazmat: !!l.hazmat, miles: l.miles,
}));

writeFileSync(
  new URL("../public/desk/data.js", import.meta.url),
  `// Generated by scripts/build_desk.mjs. Do not edit.\nwindow.DESK = ${JSON.stringify({ company: world.company, threads, gate, checks, facilities, loads })};\n`,
);
console.log(`${threads.length} threads, ${facilities.length} facilities, ${loads.length} loads`);
